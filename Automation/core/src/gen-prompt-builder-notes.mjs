// One-off generator: extracts the exact reference-sources / NCERT-KB /
// teaching-level / output-contract logic from notes-factory/index.html and
// writes it out as a standalone ES module (prompt-builder-notes.mjs), so the
// automated pipeline uses byte-identical logic to the manual browser tool
// instead of a hand-retyped (and therefore driftable) copy. Run this again
// any time notes-factory/index.html's buildPrompt()/outputContract()/
// reference-source logic changes.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..', '..', '..');
const src = fs.readFileSync(path.join(REPO_ROOT, 'notes-factory', 'index.html'), 'utf8');

function extractConst(name) {
  const re = new RegExp('const ' + name + ' = ');
  const start = src.search(re);
  if (start < 0) throw new Error('const not found: ' + name);
  const semiIdx = findStatementEnd(start);
  return src.slice(start, semiIdx + 1);
}
function extractFn(name) {
  const re = new RegExp('function ' + name + '\\(');
  const start = src.search(re);
  if (start < 0) throw new Error('function not found: ' + name);
  let i = src.indexOf('{', start);
  let depth = 0;
  for (; i < src.length; i++) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}') { depth--; if (depth === 0) { i++; break; } }
  }
  return src.slice(start, i);
}
// Finds the closing ';' of a `const NAME = {...}` or `[...]` statement by
// bracket-depth matching from the first '{' or '[' after '='.
function findStatementEnd(start) {
  const openIdx = src.slice(start).search(/[{\[]/) + start;
  const openCh = src[openIdx], closeCh = openCh === '{' ? '}' : ']';
  let depth = 0, i = openIdx;
  for (; i < src.length; i++) {
    if (src[i] === openCh) depth++;
    else if (src[i] === closeCh) { depth--; if (depth === 0) { i++; break; } }
  }
  // consume trailing `;`
  while (src[i] !== ';') i++;
  return i;
}

const pieces = [
  extractConst('REFERENCE_SOURCES_GENERAL'),
  extractConst('REFERENCE_SOURCES_BY_SUBJECT'),
  extractFn('getReferenceSources'),
  extractFn('getTeachingLevel'),
  extractFn('buildReferenceSourcesBlock'),
  extractConst('NCERT_KB_SUBJECT_MAP'),
  extractFn('buildNcertKnowledgeBaseBlock'),
  extractFn('outputContract'),
];

const header = `// AUTO-GENERATED by gen-prompt-builder-notes.mjs from notes-factory/index.html.
// Do not hand-edit — re-run the generator instead so this never drifts from
// the manual browser tool's actual buildPrompt()/outputContract() logic.
// buildReferenceSourcesBlock() below reads an 'extraSourceUrls' DOM element
// in the original; here it takes an explicit (default empty) parameter
// instead since there is no DOM in this Node context.
`;

// buildReferenceSourcesBlock in the original reads
// document.getElementById('extraSourceUrls').value — replace that single
// line with a plain parameter so this runs outside a browser.
let body = pieces.join('\n\n');
body = body.replace(
  /const extraEl = document\.getElementById\('extraSourceUrls'\);\s*\n\s*const extra = \(extraEl \? extraEl\.value : ''\)\s*\n?\s*\.split/,
  `const extra = (extraSourceUrls || '')\n    .split`
);
body = body.replace('function buildReferenceSourcesBlock(subject){', 'function buildReferenceSourcesBlock(subject, extraSourceUrls){');

const footer = `

export function buildNotesPrompt({ topic, examType, subject, hindiPercent, year, masterPromptText, extraSourceUrls }) {
  let master = masterPromptText
    .replace('{{REFERENCE_SOURCES_BLOCK}}', buildReferenceSourcesBlock(subject, extraSourceUrls) + buildNcertKnowledgeBaseBlock(subject))
    .replaceAll('{{TEACHING_LEVEL}}', getTeachingLevel(examType));

  const config = \`=== RUN THIS GENERATION WITH THESE EXACT INPUT VARIABLES ===
TOPIC: \${topic}
EXAM TYPE: \${examType}
SUBJECT: \${subject}
TARGET_YEAR: \${year} (this is the locked constant already specified inside the prompt below — do not change it)
LANGUAGE MIX: Hindi \${hindiPercent}% + English \${100 - hindiPercent}% — this OVERRIDES any Hindi/English language-mix default stated elsewhere in the master prompt below. Apply this ratio to the explanations/tricks/teacher-talk/connecting prose only — key terms, definitions, and technical labels still stay in English regardless of this split.
=== END RUN CONFIGURATION — THE FULL MASTER PROMPT FOLLOWS BELOW, UNCHANGED ===

\`;
  return config + master + outputContract();
}
`;

fs.writeFileSync(path.join(__dirname, 'prompt-builder-notes.mjs'), header + body + footer);
console.log('wrote prompt-builder-notes.mjs');
